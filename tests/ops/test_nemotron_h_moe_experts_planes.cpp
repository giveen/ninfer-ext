// The plane-addressed route of ninfer::ops::nemotron_h_moe_experts: a registered (block-scaled
// NVFP4) bank read through its four planes, which is the route the offload path stages a bank into.
//
// What it has to establish, and what each case is for:
//
//   * the decode. The bank is synthesised as *stored bytes* -- E2M1 codes, the K16M128x4 E4M3 scale
//     swizzle, and the bank's weight divisors -- and the oracle is the same formula evaluated in
//     FP64 from a host-side decode of those same bytes. A wrong scale offset, a swapped nibble, a
//     divisor applied as a multiply or a plane stride taken from the wrong layer all move the
//     weights the Op reads, so they land outside the criterion rather than inside it.
//   * the *staged* bank is the same bank at another address. The identical call is made twice: once
//     with the planes pointing at host memory (the in-place route, which for a pinned bank a kernel
//     addresses over UVA) and once at a device copy of the same bytes (the staged route). The two
//     must be bit-identical, which is the property that lets placement be an execution choice
//     rather than a semantic one.
//   * the two count paths the offload design named. A bank read with another layer's expert count
//     or another layer's plane stride indexes past the rows it owns, so both are refused here
//     before a kernel can read them.
//   * the divisor forms. This checkpoint stores one weight divisor per bank matrix; a per-expert
//     divisor array is the other form the layout admits, and the Op resolves both.
#include "ninfer/ops/nemotron_h_moe_experts.h"
#include "ninfer/ops/offload_moe.h"

